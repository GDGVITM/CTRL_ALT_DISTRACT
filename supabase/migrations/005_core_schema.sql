-- Description: Core competition schema — event config, languages, problems + hidden tests,
--              participations, per-round attempts, submissions, distraction log and proctoring alerts.
--
-- Access model: the FastAPI backend connects as the `postgres` role (bypasses RLS) and is the only
-- writer. RLS is enabled on every table with NO policies for anon/authenticated, so the Supabase
-- REST API cannot read hidden test cases or tamper with scores. The one exception is `event_config`,
-- which authenticated users may SELECT so the frontend can subscribe to Realtime status changes.

-- ---------------------------------------------------------------------------
-- 0. Security fix: never trust a client-supplied role on sign-up.
--    Previously `raw_user_meta_data->>'role' = 'admin'` made any visitor an admin.
--    Admins are now promoted server-side (see `python -m app.cli make-admin <email>`).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO public.profiles (id, email, full_name, role)
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'full_name', ''),
        'participant'
    )
    ON CONFLICT (id) DO UPDATE
    SET email = EXCLUDED.email,
        full_name = EXCLUDED.full_name;

    UPDATE auth.users
    SET raw_app_meta_data = COALESCE(raw_app_meta_data, '{}'::jsonb) || jsonb_build_object('role', 'participant')
    WHERE id = NEW.id;

    RETURN NEW;
END;
$$;

