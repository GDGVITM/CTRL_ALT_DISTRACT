-- ---------------------------------------------------------------------------
-- 4. Problems and test cases
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.problems (
    id              SERIAL PRIMARY KEY,
    round_no        INTEGER NOT NULL UNIQUE CHECK (round_no > 0),
    slug            TEXT    NOT NULL UNIQUE,
    title           TEXT    NOT NULL,
    difficulty      TEXT    NOT NULL CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    tags            TEXT[]  NOT NULL DEFAULT '{}',
    description     JSONB   NOT NULL DEFAULT '[]',      -- array of paragraphs
    input_format    TEXT    NOT NULL DEFAULT '',
    output_format   TEXT    NOT NULL DEFAULT '',
    examples        JSONB   NOT NULL DEFAULT '[]',      -- [{input, output, explanation}]
    constraints     TEXT[]  NOT NULL DEFAULT '{}',
    hints           TEXT[]  NOT NULL DEFAULT '{}',
    signature       JSONB   NOT NULL,                   -- {function, params:[{name,type}], returns}
    time_limit_ms   INTEGER NOT NULL DEFAULT 1500,      -- per test case, before the language multiplier
    memory_limit_kb INTEGER NOT NULL DEFAULT 262144,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.problem_tests (
    id               BIGSERIAL PRIMARY KEY,
    problem_id       INTEGER NOT NULL REFERENCES public.problems(id) ON DELETE CASCADE,
    ord              INTEGER NOT NULL,
    stdin            TEXT    NOT NULL,                  -- one case in the harness wire format
    expected         TEXT    NOT NULL,                  -- expected output line
    is_sample        BOOLEAN NOT NULL DEFAULT FALSE,    -- samples are used by RUN and shown to players
    display_input    TEXT,
    display_expected TEXT,
    UNIQUE (problem_id, ord)
);
CREATE INDEX IF NOT EXISTS idx_problem_tests_problem ON public.problem_tests(problem_id, ord);

