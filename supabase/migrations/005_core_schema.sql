CREATE TABLE IF NOT EXISTS public.participations (
    user_id              UUID PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
    status               participant_status NOT NULL DEFAULT 'joined',
    joined_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at           TIMESTAMPTZ,
    finished_at          TIMESTAMPTZ,
    current_round        INTEGER NOT NULL DEFAULT 0,
    distraction_order    INTEGER[] NOT NULL,            -- per-player shuffled distraction indices
    round_pts            INTEGER NOT NULL DEFAULT 0,
    bonus_pts            INTEGER NOT NULL DEFAULT 0,
    total_pts            INTEGER GENERATED ALWAYS AS (round_pts + bonus_pts) STORED,
    total_time_ms        BIGINT  NOT NULL DEFAULT 0,
    solved_count         INTEGER NOT NULL DEFAULT 0,
    distractions_total   INTEGER NOT NULL DEFAULT 0,
    distractions_cleared INTEGER NOT NULL DEFAULT 0,
    active_client        TEXT,                           -- tab/device id, used to flag multi-session play
    last_seen_at         TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_participations_rank
    ON public.participations (total_pts DESC, total_time_ms ASC, joined_at ASC);
CREATE INDEX IF NOT EXISTS idx_participations_status ON public.participations(status);

CREATE TABLE IF NOT EXISTS public.round_attempts (
    user_id           UUID    NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    round_no          INTEGER NOT NULL,
    problem_id        INTEGER NOT NULL REFERENCES public.problems(id),
    status            round_status NOT NULL DEFAULT 'active',
    started_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at       TIMESTAMPTZ,
    paused_ms         INTEGER NOT NULL DEFAULT 0,       -- time spent inside distractions (timer is frozen)
    pause_started_at  TIMESTAMPTZ,
    submit_lock_until TIMESTAMPTZ,                      -- set while a submission is being judged; blocks expiry
    time_ms           INTEGER,                          -- active time used, set when resolved
    points            INTEGER NOT NULL DEFAULT 0,
    bonus             INTEGER NOT NULL DEFAULT 0,
    distraction_index INTEGER NOT NULL,
    distraction_at    INTEGER NOT NULL,                 -- active seconds into the round when it fires
    distraction_state TEXT    NOT NULL DEFAULT 'pending'
        CHECK (distraction_state IN ('pending', 'active', 'cleared', 'missed')),
    PRIMARY KEY (user_id, round_no)
);
CREATE INDEX IF NOT EXISTS idx_round_attempts_status ON public.round_attempts(status);

